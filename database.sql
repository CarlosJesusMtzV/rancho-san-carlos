-- Ficha del animal con especie, raza, lote y último peso registrado.
CREATE VIEW v_animal_profiles AS
SELECT
    a.id AS animal_id,
    a.visual_tag,
    a.official_tag,
    s.name AS species_name,
    b.name AS breed_name,
    l.code AS lot_code,
    a.sex,
    a.birth_date,
    a.production_stage,
    a.lifecycle_status,
    a.sire_id,
    a.dam_id,
    w.weight_kg AS last_weight_kg,
    w.weighed_on AS last_weighed_on
FROM animals a
JOIN species s ON s.id = a.species_id
JOIN breeds b ON b.id = a.breed_id
LEFT JOIN animal_lots l ON l.id = a.lot_id
LEFT JOIN LATERAL (
    SELECT wr.weight_kg, wr.weighed_on
    FROM weight_records wr
    WHERE wr.animal_id = a.id AND wr.deleted_at IS NULL
    ORDER BY wr.weighed_on DESC
    LIMIT 1
) w ON true
WHERE a.deleted_at IS NULL;

-- Animales con retiro vigente. *_allowed_from es el primer día en que su leche puede ir a quesería
-- o en que pueden sacrificarse; NULL si ese retiro no aplica hoy.
CREATE VIEW v_active_withdrawals AS
SELECT
    a.id AS animal_id,
    a.visual_tag,
    a.species_id,
    max(he.event_date + t.milk_withdrawal_days)
        FILTER (WHERE he.event_date + t.milk_withdrawal_days > CURRENT_DATE) AS milk_allowed_from,
    max(he.event_date + t.meat_withdrawal_days)
        FILTER (WHERE he.event_date + t.meat_withdrawal_days > CURRENT_DATE) AS meat_allowed_from
FROM treatments t
JOIN health_events he ON he.id = t.health_event_id
JOIN animals a ON a.id = he.animal_id
WHERE t.deleted_at IS NULL
  AND he.deleted_at IS NULL
  AND a.deleted_at IS NULL
  AND (
      he.event_date + t.milk_withdrawal_days > CURRENT_DATE
      OR he.event_date + t.meat_withdrawal_days > CURRENT_DATE
  )
GROUP BY a.id, a.visual_tag, a.species_id;

-- Becerros (bovinos activos menores de 18 meses, sin vender) con su avance hacia la meta de venta:
-- edad promedio de 8 meses o peso aproximado de 150 kg. Ajustar las metas aquí si cambian.
CREATE VIEW v_calf_sale_candidates AS
WITH calves AS (
    SELECT
        a.id AS animal_id,
        a.visual_tag,
        a.official_tag,
        a.sex,
        a.lot_id,
        a.birth_date,
        (date_part('year', age(CURRENT_DATE, a.birth_date)) * 12
            + date_part('month', age(CURRENT_DATE, a.birth_date)))::integer AS age_months,
        w.weight_kg AS last_weight_kg,
        w.weighed_on AS last_weighed_on
    FROM animals a
    LEFT JOIN LATERAL (
        SELECT wr.weight_kg, wr.weighed_on
        FROM weight_records wr
        WHERE wr.animal_id = a.id AND wr.deleted_at IS NULL
        ORDER BY wr.weighed_on DESC
        LIMIT 1
    ) w ON true
    WHERE a.species_id = 1
      AND a.lifecycle_status = 'active'
      AND a.deleted_at IS NULL
      AND a.birth_date > CURRENT_DATE - INTERVAL '18 months'
      AND NOT EXISTS (
          SELECT 1 FROM order_items oi
          WHERE oi.animal_id = a.id AND oi.deleted_at IS NULL
      )
)
SELECT
    c.*,
    aw.meat_allowed_from,
    (coalesce(c.age_months, 0) >= 8 OR coalesce(c.last_weight_kg, 0) >= 150) AS reached_sale_target
FROM calves c
LEFT JOIN v_active_withdrawals aw ON aw.animal_id = c.animal_id;

-- Trazabilidad pública de un lote de queso hasta su lote de leche.
CREATE VIEW v_cheese_batch_traceability AS
SELECT
    cb.id AS cheese_batch_id,
    cb.code AS batch_code,
    p.sku,
    p.name AS product_name,
    cb.made_on,
    cb.expires_on,
    cb.liters_used,
    cb.kg_produced,
    cb.kg_available,
    ml.code AS milk_lot_code,
    ml.collection_date,
    count(DISTINCT mr.animal_id) AS goats_milked,
    ml.total_liters AS liters_collected
FROM cheese_batches cb
JOIN products p ON p.id = cb.product_id
JOIN milk_lots ml ON ml.id = cb.milk_lot_id
LEFT JOIN milk_records mr ON mr.milk_lot_id = ml.id AND mr.deleted_at IS NULL
WHERE cb.deleted_at IS NULL
GROUP BY cb.id, p.sku, p.name, ml.code, ml.collection_date, ml.total_liters;

-- Totales de pedidos y de órdenes de compra (antes columnas calculadas a mano).
CREATE VIEW v_order_totals AS
SELECT
    o.id AS order_id,
    o.customer_id,
    o.order_status,
    count(oi.id) AS item_count,
    coalesce(sum(round(oi.quantity * oi.unit_price, 2)), 0) AS total
FROM orders o
LEFT JOIN order_items oi ON oi.order_id = o.id AND oi.deleted_at IS NULL
WHERE o.deleted_at IS NULL
GROUP BY o.id;

CREATE VIEW v_purchase_order_totals AS
SELECT
    po.id AS purchase_order_id,
    po.supplier_id,
    po.order_status,
    count(poi.id) AS item_count,
    coalesce(sum(round(poi.quantity * poi.unit_cost, 2)), 0) AS total
FROM purchase_orders po
LEFT JOIN purchase_order_items poi ON poi.purchase_order_id = po.id AND poi.deleted_at IS NULL
WHERE po.deleted_at IS NULL
GROUP BY po.id;

