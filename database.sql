    CONSTRAINT fk_breeds_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_breeds_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_breeds_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);

