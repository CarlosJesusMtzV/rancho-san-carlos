-- -----------------------------------------------------------------------------
-- Reproducción
-- -----------------------------------------------------------------------------

-- Montas naturales. Hembra y semental son de la misma especie (llaves compuestas).
CREATE TABLE breeding_events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id smallint NOT NULL,
    female_id integer NOT NULL,
    male_id integer NOT NULL,
    mating_date date NOT NULL,
    expected_due_date date NOT NULL,
    outcome varchar(10) NOT NULL DEFAULT 'pending',
    notes varchar(255),
    status smallint NOT NULL DEFAULT 1,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by integer,
    updated_at timestamptz,
    deleted_by integer,
    deleted_at timestamptz,
    CONSTRAINT ck_breeding_events_pair CHECK (male_id <> female_id),
    CONSTRAINT ck_breeding_events_due CHECK (expected_due_date > mating_date),
    CONSTRAINT ck_breeding_events_outcome CHECK (outcome IN ('pending', 'pregnant', 'open', 'aborted', 'delivered')),
    CONSTRAINT ck_breeding_events_record_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_breeding_events_species_id FOREIGN KEY (species_id) REFERENCES species (id),
    CONSTRAINT fk_breeding_events_female_id_species_id FOREIGN KEY (female_id, species_id) REFERENCES animals (id, species_id),
    CONSTRAINT fk_breeding_events_male_id_species_id FOREIGN KEY (male_id, species_id) REFERENCES animals (id, species_id),
    CONSTRAINT fk_breeding_events_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_breeding_events_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_breeding_events_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);

-- Partos. Las crías vivas se dan de alta en animals con birth_event_id; las muertas al nacer solo se cuentan.
CREATE TABLE birth_events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dam_id integer NOT NULL,
    breeding_event_id integer,
    birth_date date NOT NULL,
    offspring_count smallint NOT NULL,
    stillborn_count smallint NOT NULL DEFAULT 0,
    complications varchar(255),
    status smallint NOT NULL DEFAULT 1,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by integer,
    updated_at timestamptz,
    deleted_by integer,
    deleted_at timestamptz,
    CONSTRAINT ck_birth_events_offspring CHECK (offspring_count >= 0 AND stillborn_count >= 0 AND offspring_count + stillborn_count > 0),
    CONSTRAINT ck_birth_events_record_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_birth_events_dam_id FOREIGN KEY (dam_id) REFERENCES animals (id),
    CONSTRAINT fk_birth_events_breeding_event_id FOREIGN KEY (breeding_event_id) REFERENCES breeding_events (id),
    CONSTRAINT fk_birth_events_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_birth_events_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_birth_events_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);


