-- Primer día permitido para un animal según sus tratamientos ('milk' o 'meat'); NULL si no hay retiro.
CREATE FUNCTION fn_withdrawal_allowed_from(p_animal_id integer, p_kind text, p_on date)
RETURNS date
LANGUAGE sql
STABLE
AS $$
    SELECT max(he.event_date + CASE p_kind WHEN 'milk' THEN t.milk_withdrawal_days ELSE t.meat_withdrawal_days END)
    FROM treatments t
    JOIN health_events he ON he.id = t.health_event_id
    WHERE he.animal_id = p_animal_id
      AND t.deleted_at IS NULL
      AND he.deleted_at IS NULL
      AND he.event_date <= p_on
      AND he.event_date + CASE p_kind WHEN 'milk' THEN t.milk_withdrawal_days ELSE t.meat_withdrawal_days END > p_on
$$;

-- Ordeña: solo cabras hembra activas y sin retiro de leche en la fecha de la ordeña.
CREATE FUNCTION fn_check_milk_record()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_sex char(1);
    v_lifecycle varchar(12);
    v_tag varchar(30);
    v_date date;
    v_allowed date;
BEGIN
    SELECT sex, lifecycle_status, visual_tag INTO v_sex, v_lifecycle, v_tag FROM animals WHERE id = NEW.animal_id;
    IF v_sex IS DISTINCT FROM 'F' THEN
        RAISE EXCEPTION 'Solo se pueden ordeñar cabras hembra.' USING ERRCODE = 'check_violation';
    END IF;
    IF v_lifecycle IS DISTINCT FROM 'active' THEN
        RAISE EXCEPTION 'La cabra % ya no está activa en el hato.', v_tag USING ERRCODE = 'check_violation';
    END IF;
    SELECT collection_date INTO v_date FROM milk_lots WHERE id = NEW.milk_lot_id;
    v_allowed := fn_withdrawal_allowed_from(NEW.animal_id, 'milk', v_date);
    IF v_allowed IS NOT NULL THEN
        RAISE EXCEPTION 'La cabra % tiene retiro de leche; su leche puede usarse a partir del %.', v_tag, to_char(v_allowed, 'DD/MM/YYYY')
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_milk_records_check
BEFORE INSERT OR UPDATE OF animal_id, milk_lot_id ON milk_records
FOR EACH ROW EXECUTE FUNCTION fn_check_milk_record();

-- Matanza de cabritos: sin retiro de carne en la fecha de sacrificio.
CREATE FUNCTION fn_check_kid_slaughter()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_allowed date;
BEGIN
    v_allowed := fn_withdrawal_allowed_from(NEW.animal_id, 'meat', NEW.slaughter_date);
    IF v_allowed IS NOT NULL THEN
        RAISE EXCEPTION 'El cabrito tiene retiro de carne; puede sacrificarse a partir del %.', to_char(v_allowed, 'DD/MM/YYYY')
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_kid_slaughters_check
BEFORE INSERT OR UPDATE OF animal_id, slaughter_date ON kid_slaughters
FOR EACH ROW EXECUTE FUNCTION fn_check_kid_slaughter();

