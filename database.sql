);

-- Ejemplar individual. Integra genealogía (antes RegistroGenetico) y datos de nacimiento (antes Cria).
CREATE TABLE animals (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visual_tag varchar(30) NOT NULL,
    official_tag varchar(30),
    species_id smallint NOT NULL,
    breed_id integer NOT NULL,
    lot_id integer,
    sex char(1) NOT NULL,
    birth_date date,
    production_stage varchar(30),
    origin varchar(20) NOT NULL DEFAULT 'born_on_ranch',
    birth_event_id integer,
    birth_weight_kg numeric(6,2),
    sire_id integer,
    dam_id integer,
    genetics_notes text,
    lifecycle_status varchar(12) NOT NULL DEFAULT 'active',
    exit_date date,
    status smallint NOT NULL DEFAULT 1,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by integer,
    updated_at timestamptz,
    deleted_by integer,
    deleted_at timestamptz,
    CONSTRAINT uq_animals_visual_tag UNIQUE (visual_tag),
    CONSTRAINT uq_animals_official_tag UNIQUE (official_tag),
    CONSTRAINT uq_animals_id_species UNIQUE (id, species_id),
    CONSTRAINT ck_animals_sex CHECK (sex IN ('M', 'F')),
    CONSTRAINT ck_animals_origin CHECK (origin IN ('born_on_ranch', 'purchased')),
    CONSTRAINT ck_animals_birth_weight CHECK (birth_weight_kg IS NULL OR birth_weight_kg > 0),
    CONSTRAINT ck_animals_parents CHECK (sire_id IS DISTINCT FROM id AND dam_id IS DISTINCT FROM id),
    CONSTRAINT ck_animals_lifecycle CHECK (lifecycle_status IN ('active', 'sold', 'slaughtered', 'dead', 'culled')),
    CONSTRAINT ck_animals_exit CHECK ((lifecycle_status = 'active') = (exit_date IS NULL)),
    CONSTRAINT ck_animals_record_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_animals_species_id FOREIGN KEY (species_id) REFERENCES species (id),
    CONSTRAINT fk_animals_breed_id_species_id FOREIGN KEY (breed_id, species_id) REFERENCES breeds (id, species_id),
    CONSTRAINT fk_animals_lot_id_species_id FOREIGN KEY (lot_id, species_id) REFERENCES animal_lots (id, species_id),
    CONSTRAINT fk_animals_sire_id FOREIGN KEY (sire_id) REFERENCES animals (id),
    CONSTRAINT fk_animals_dam_id FOREIGN KEY (dam_id) REFERENCES animals (id),
    CONSTRAINT fk_animals_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_animals_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_animals_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);

