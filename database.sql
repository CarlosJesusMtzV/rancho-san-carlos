-- -----------------------------------------------------------------------------
-- Hato: especies, razas, lotes y animales
-- -----------------------------------------------------------------------------

-- Solo dos especies con propósito fijo: bovino para carne, caprino para cabritos y leche.
CREATE TABLE species (
    id smallint PRIMARY KEY,
    name varchar(20) NOT NULL,
    production_purpose varchar(20) NOT NULL,
    description varchar(255),
    status smallint NOT NULL DEFAULT 1,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by integer,
    updated_at timestamptz,
    deleted_by integer,
    deleted_at timestamptz,
    CONSTRAINT uq_species_name UNIQUE (name),
    CONSTRAINT ck_species_catalog CHECK (
        (id = 1 AND name = 'Bovino' AND production_purpose = 'meat')
        OR (id = 2 AND name = 'Caprino' AND production_purpose = 'kids_and_milk')
    ),
    CONSTRAINT ck_species_record_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_species_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_species_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_species_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);

