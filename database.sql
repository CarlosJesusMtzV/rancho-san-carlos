-- =============================================================================
-- Rancho San Carlos y La Cremería San Carlos · Castaños, Coahuila
-- Esquema PostgreSQL del sistema de gestión ganadera y quesera.
--
-- Alcance del dominio:
--   * Bovinos: únicamente carne. Se venden vivos: becerros de ~8 meses y ~150 kg.
--   * Caprinos: cabritos (en pie o sacrificados y pelados, en canal) y leche.
--     Los tres quesos son exclusivamente de leche de cabra.
--   * Quesería artesanal: lotes de queso trazables hasta el lote de leche.
--
-- Convenciones del template TecNM: objetos en snake_case e identificadores en
-- inglés. La equivalencia con el diseño original en español está en
-- specs/database.spec.md.
--
-- Todas las tablas llevan las columnas de auditoría del diseño original:
--   status (1 activo, 0 inactivo), created_by/at, updated_by/at, deleted_by/at.
--
-- Se ejecuta solo al inicializar un volumen PostgreSQL nuevo (ver docs/setup.md).
-- Editarlo no migra una base existente.
-- =============================================================================

BEGIN;

-- Fechas en hora de Coahuila (UTC-6): CURRENT_DATE y la conversión de timestamptz a date
-- deciden los retiros sanitarios, así que deben coincidir con el día del rancho y no con UTC.
DO $$
BEGIN
    EXECUTE format('ALTER DATABASE %I SET timezone TO %L', current_database(), 'America/Monterrey');
END
$$;
SET timezone TO 'America/Monterrey';


-- -----------------------------------------------------------------------------
-- Seguridad y acceso
-- -----------------------------------------------------------------------------

-- Cuentas del sistema; origen de las columnas de auditoría.
CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(64) NOT NULL,
    password_hash varchar(512) NOT NULL,
    email varchar(254) NOT NULL,
    role varchar(16) NOT NULL DEFAULT 'operator',
    employee_id integer,
    status smallint NOT NULL DEFAULT 1,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by integer,
    updated_at timestamptz,
    deleted_by integer,
    deleted_at timestamptz,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_employee_id UNIQUE (employee_id),
    CONSTRAINT ck_users_role CHECK (role IN ('admin', 'manager', 'operator', 'vet', 'sales')),
    CONSTRAINT ck_users_record_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_users_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_users_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_users_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);


