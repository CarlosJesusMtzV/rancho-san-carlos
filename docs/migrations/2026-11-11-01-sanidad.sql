-- Migración: visitas del veterinario y retiros por medicamento (módulo Sanidad).
--
-- Solo para bases creadas con el database.sql anterior al módulo Sanidad.
-- Una base nueva ya trae estos cambios: no ejecutar ahí.
--
-- Uso (desde la raíz del proyecto, con Docker en marcha):
--   docker compose exec -T db psql -U tecnm_app -d tecnm_template -v ON_ERROR_STOP=1 < docs/migrations/2026-11-11-01-sanidad.sql
-- =============================================================================

BEGIN;

-- Fechas en hora de Coahuila para que los retiros cuenten el día del rancho, no el de UTC.
DO $$
BEGIN
    EXECUTE format('ALTER DATABASE %I SET timezone TO %L', current_database(), 'America/Monterrey');
END
$$;

-- Medicamentos sin existencias: guardan los días de retiro sugeridos.
ALTER TABLE supplies
    ADD COLUMN default_milk_withdrawal_days smallint NOT NULL DEFAULT 0,
    ADD COLUMN default_meat_withdrawal_days smallint NOT NULL DEFAULT 0,
    ADD CONSTRAINT uq_supplies_commercial_name UNIQUE (commercial_name),
    ADD CONSTRAINT ck_supplies_default_withdrawal CHECK (default_milk_withdrawal_days >= 0 AND default_meat_withdrawal_days >= 0);

-- Visitas del veterinario externo.
CREATE TABLE vet_visits (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_date date NOT NULL,
    vet_name varchar(120) NOT NULL,
    service_fee numeric(10,2) NOT NULL DEFAULT 0,
    medication_cost numeric(10,2) NOT NULL DEFAULT 0,
    notes varchar(255),
    status smallint NOT NULL DEFAULT 1,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by integer,
    updated_at timestamptz,
    deleted_by integer,
    deleted_at timestamptz,
    CONSTRAINT ck_vet_visits_amounts CHECK (service_fee >= 0 AND medication_cost >= 0),
    CONSTRAINT ck_vet_visits_record_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_vet_visits_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_vet_visits_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_vet_visits_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);

-- El evento sanitario apunta a la visita (opcional) en lugar de a un empleado.
DROP INDEX IF EXISTS ix_health_events_vet_employee_id;
ALTER TABLE health_events DROP COLUMN vet_employee_id;
ALTER TABLE health_events
    ADD COLUMN vet_visit_id integer,
    ADD CONSTRAINT fk_health_events_vet_visit_id FOREIGN KEY (vet_visit_id) REFERENCES vet_visits (id);
CREATE INDEX ix_health_events_vet_visit_id ON health_events (vet_visit_id);

-- Tipos de insumo de sanidad.
INSERT INTO supply_types (id, name, category) VALUES
    (1, 'Medicamento', 'medicine'),
    (2, 'Vacuna', 'vaccine'),
    (3, 'Desparasitante', 'medicine')
ON CONFLICT DO NOTHING;
SELECT setval(pg_get_serial_sequence('supply_types', 'id'), greatest(3, (SELECT max(id) FROM supply_types)));

COMMIT;
