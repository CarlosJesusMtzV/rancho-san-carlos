BEGIN;

-- Solo monta natural: se quitan método e inseminación; la monta siempre lleva semental.
-- Si ya había montas registradas a mano, este paso falla y hay que revisarlas antes.
ALTER TABLE breeding_events
    DROP CONSTRAINT ck_breeding_events_method,
    DROP CONSTRAINT ck_breeding_events_pair,
    DROP CONSTRAINT ck_breeding_events_due,
    DROP CONSTRAINT ck_breeding_events_outcome,
    DROP CONSTRAINT fk_breeding_events_female_id,
    DROP CONSTRAINT fk_breeding_events_male_id,
    DROP CONSTRAINT fk_breeding_events_semen_supply_id;
DROP INDEX IF EXISTS ix_breeding_events_female_id;
DROP INDEX IF EXISTS ix_breeding_events_male_id;
DROP INDEX IF EXISTS ix_breeding_events_semen_supply_id;
ALTER TABLE breeding_events DROP COLUMN method, DROP COLUMN semen_supply_id;
ALTER TABLE breeding_events RENAME COLUMN event_date TO mating_date;
ALTER TABLE breeding_events
    ADD COLUMN species_id smallint NOT NULL,
    ADD COLUMN notes varchar(255),
    ALTER COLUMN male_id SET NOT NULL,
    ALTER COLUMN expected_due_date SET NOT NULL,
    ADD CONSTRAINT ck_breeding_events_pair CHECK (male_id <> female_id),
    ADD CONSTRAINT ck_breeding_events_due CHECK (expected_due_date > mating_date),
    ADD CONSTRAINT ck_breeding_events_outcome CHECK (outcome IN ('pending', 'pregnant', 'open', 'aborted', 'delivered')),
    ADD CONSTRAINT fk_breeding_events_species_id FOREIGN KEY (species_id) REFERENCES species (id),
    ADD CONSTRAINT fk_breeding_events_female_id_species_id FOREIGN KEY (female_id, species_id) REFERENCES animals (id, species_id),
    ADD CONSTRAINT fk_breeding_events_male_id_species_id FOREIGN KEY (male_id, species_id) REFERENCES animals (id, species_id);
CREATE INDEX ix_breeding_events_species_id ON breeding_events (species_id);
CREATE INDEX ix_breeding_events_female_id_species_id ON breeding_events (female_id, species_id);
CREATE INDEX ix_breeding_events_male_id_species_id ON breeding_events (male_id, species_id);

-- Partos: crías vivas y muertas al nacer; una monta, un parto.
ALTER TABLE birth_events
    DROP CONSTRAINT ck_birth_events_offspring,
    ADD COLUMN stillborn_count smallint NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_birth_events_offspring CHECK (offspring_count >= 0 AND stillborn_count >= 0 AND offspring_count + stillborn_count > 0);
DROP INDEX IF EXISTS ix_birth_events_breeding_event_id;
CREATE UNIQUE INDEX uq_birth_events_breeding_active ON birth_events (breeding_event_id)
    WHERE breeding_event_id IS NOT NULL AND deleted_at IS NULL;

-- Diagnóstico de preñez en las visitas del veterinario.
CREATE TABLE pregnancy_checks (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    breeding_event_id integer NOT NULL,
    vet_visit_id integer NOT NULL,
    check_date date NOT NULL,
    result varchar(10) NOT NULL,
    notes varchar(255),
    status smallint NOT NULL DEFAULT 1,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by integer,
    updated_at timestamptz,
    deleted_by integer,
    deleted_at timestamptz,
    CONSTRAINT uq_pregnancy_checks_breeding_visit UNIQUE (breeding_event_id, vet_visit_id),
    CONSTRAINT ck_pregnancy_checks_result CHECK (result IN ('pregnant', 'open', 'aborted')),
    CONSTRAINT ck_pregnancy_checks_record_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_pregnancy_checks_breeding_event_id FOREIGN KEY (breeding_event_id) REFERENCES breeding_events (id),
    CONSTRAINT fk_pregnancy_checks_vet_visit_id FOREIGN KEY (vet_visit_id) REFERENCES vet_visits (id),
    CONSTRAINT fk_pregnancy_checks_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_pregnancy_checks_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_pregnancy_checks_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);
CREATE INDEX ix_pregnancy_checks_vet_visit_id ON pregnancy_checks (vet_visit_id);

COMMIT;
