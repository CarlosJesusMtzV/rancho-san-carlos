-- Trazabilidad pública de una tanda de queso hasta la ordeña del día, por presentación.
CREATE VIEW v_cheese_batch_traceability AS
SELECT
    cb.id AS cheese_batch_id,
    cb.code AS batch_code,
    p.sku,
    p.name AS product_name,
    p.sale_unit,
    o.quantity,
    cb.made_on,
    cb.expires_on,
    cb.liters_used,
    ml.code AS milk_lot_code,
    ml.collection_date,
    (SELECT count(*) FROM milk_records mr WHERE mr.milk_lot_id = ml.id AND mr.deleted_at IS NULL) AS goats_milked,
    ml.total_liters AS liters_collected
FROM cheese_batches cb
JOIN cheese_batch_outputs o ON o.cheese_batch_id = cb.id AND o.deleted_at IS NULL
JOIN products p ON p.id = o.product_id
JOIN milk_lots ml ON ml.id = cb.milk_lot_id
WHERE cb.deleted_at IS NULL;

-- Existencias de queso por entrada (presentación de tanda o compra): entró - mermas - vendido.
-- Lo vendido cuenta en pedidos confirmados o entregados.
CREATE VIEW v_cheese_stock AS
WITH entries AS (
    SELECT 'batch'::text AS source, o.id AS source_id, cb.id AS parent_id, cb.code, o.product_id,
           cb.made_on AS entry_date, cb.expires_on, o.quantity AS quantity_in
    FROM cheese_batch_outputs o
    JOIN cheese_batches cb ON cb.id = o.cheese_batch_id
    WHERE o.deleted_at IS NULL AND cb.deleted_at IS NULL
    UNION ALL
    SELECT 'purchase'::text, cp.id, cp.id, cp.code, cp.product_id, cp.purchase_date, cp.expires_on, cp.quantity
    FROM cheese_purchases cp
    WHERE cp.deleted_at IS NULL
), adjusted AS (
    SELECT CASE WHEN a.cheese_batch_output_id IS NOT NULL THEN 'batch' ELSE 'purchase' END AS source,
           coalesce(a.cheese_batch_output_id, a.cheese_purchase_id) AS source_id,
           sum(a.quantity) AS quantity
    FROM cheese_stock_adjustments a
    WHERE a.deleted_at IS NULL
    GROUP BY 1, 2
), sold AS (
    SELECT CASE WHEN oi.cheese_batch_output_id IS NOT NULL THEN 'batch' ELSE 'purchase' END AS source,
           coalesce(oi.cheese_batch_output_id, oi.cheese_purchase_id) AS source_id,
           sum(oi.quantity) AS quantity
    FROM order_items oi
    JOIN orders od ON od.id = oi.order_id
    WHERE oi.deleted_at IS NULL AND od.deleted_at IS NULL
      AND od.order_status IN ('confirmed', 'delivered')
      AND num_nonnulls(oi.cheese_batch_output_id, oi.cheese_purchase_id) = 1
    GROUP BY 1, 2
)
SELECT
    e.source,
    e.source_id,
    e.parent_id,
    e.code,
    e.product_id,
    p.sku,
    p.name AS product_name,
    p.sale_unit,
    e.entry_date,
    e.expires_on,
    e.quantity_in,
    coalesce(ad.quantity, 0) AS adjusted,
    coalesce(so.quantity, 0) AS sold,
    e.quantity_in - coalesce(ad.quantity, 0) - coalesce(so.quantity, 0) AS available
FROM entries e
JOIN products p ON p.id = e.product_id
LEFT JOIN adjusted ad ON ad.source = e.source AND ad.source_id = e.source_id
LEFT JOIN sold so ON so.source = e.source AND so.source_id = e.source_id;

-- Quesería: cantidad ya consumida (mermas y ventas confirmadas o entregadas) de una presentación o de una compra.
CREATE FUNCTION fn_cheese_consumed(p_output_id integer, p_purchase_id integer)
RETURNS numeric
LANGUAGE sql
STABLE
AS $$
    SELECT coalesce((
        SELECT sum(a.quantity)
        FROM cheese_stock_adjustments a
        WHERE a.deleted_at IS NULL
          AND (a.cheese_batch_output_id = p_output_id OR a.cheese_purchase_id = p_purchase_id)
    ), 0) + coalesce((
        SELECT sum(oi.quantity)
        FROM order_items oi
        JOIN orders od ON od.id = oi.order_id
        WHERE oi.deleted_at IS NULL AND od.deleted_at IS NULL
          AND od.order_status IN ('confirmed', 'delivered')
          AND (oi.cheese_batch_output_id = p_output_id OR oi.cheese_purchase_id = p_purchase_id)
    ), 0);
$$;

-- Quesería: el producto es del tipo esperado (queso propio o de reventa) y las piezas van enteras.
CREATE FUNCTION fn_check_cheese_product(p_product_id integer, p_quantity numeric, p_kind varchar)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_kind varchar(10);
    v_unit varchar(10);
    v_name varchar(120);
BEGIN
    SELECT pt.kind, p.sale_unit, p.name INTO v_kind, v_unit, v_name
    FROM products p
    JOIN product_types pt ON pt.id = p.product_type_id
    WHERE p.id = p_product_id;
    IF v_kind IS DISTINCT FROM p_kind THEN
        IF p_kind = 'cheese' THEN
            RAISE EXCEPTION 'Una tanda solo produce queso propio; % no lo es.', coalesce(v_name, 'el producto elegido')
                USING ERRCODE = 'check_violation';
        END IF;
        RAISE EXCEPTION 'Solo se compra queso de reventa; % no lo es.', coalesce(v_name, 'el producto elegido')
            USING ERRCODE = 'check_violation';
    END IF;
    IF v_unit = 'piece' AND p_quantity <> trunc(p_quantity) THEN
        RAISE EXCEPTION '% se cuenta en piezas enteras.', v_name USING ERRCODE = 'check_violation';
    END IF;
END;
$$;

-- Tanda: la ordeña sigue vigente, no cambia, la tanda no es anterior a ella ni usa más litros de los ordeñados,
-- y no se elimina si ya salió queso de ella.
CREATE FUNCTION fn_check_cheese_batch()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_date date;
    v_liters numeric(8,2);
    v_deleted timestamptz;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.deleted_at IS NOT NULL THEN
        IF OLD.deleted_at IS NULL AND EXISTS (
            SELECT 1 FROM cheese_batch_outputs o
            WHERE o.cheese_batch_id = NEW.id AND o.deleted_at IS NULL AND fn_cheese_consumed(o.id, NULL) > 0
        ) THEN
            RAISE EXCEPTION 'De la tanda % ya hay mermas o ventas; no se puede eliminar.', NEW.code USING ERRCODE = 'check_violation';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP = 'UPDATE' AND NEW.milk_lot_id <> OLD.milk_lot_id THEN
        RAISE EXCEPTION 'La ordeña de una tanda no se cambia; elimina la tanda y regístrala de nuevo.' USING ERRCODE = 'check_violation';
    END IF;
    SELECT collection_date, total_liters, deleted_at INTO v_date, v_liters, v_deleted FROM milk_lots WHERE id = NEW.milk_lot_id;
    IF v_deleted IS NOT NULL THEN
        RAISE EXCEPTION 'La ordeña elegida fue eliminada.' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.made_on < v_date THEN
        RAISE EXCEPTION 'La tanda no puede elaborarse antes de la ordeña del %.', to_char(v_date, 'DD/MM/YYYY')
            USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.liters_used > v_liters THEN
        RAISE EXCEPTION 'La tanda usa % L, pero la ordeña del % juntó % L.', NEW.liters_used, to_char(v_date, 'DD/MM/YYYY'), v_liters
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_cheese_batches_check
BEFORE INSERT OR UPDATE OF milk_lot_id, made_on, liters_used, deleted_at ON cheese_batches
FOR EACH ROW EXECUTE FUNCTION fn_check_cheese_batch();

-- Presentación de una tanda: solo queso propio, piezas enteras y nunca por debajo de lo ya consumido.
CREATE FUNCTION fn_check_cheese_batch_output()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_consumed numeric;
    v_name varchar(120);
BEGIN
    IF NEW.deleted_at IS NULL THEN
        PERFORM fn_check_cheese_product(NEW.product_id, NEW.quantity, 'cheese');
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF NEW.product_id <> OLD.product_id THEN
            RAISE EXCEPTION 'El producto de una presentación no se cambia.' USING ERRCODE = 'check_violation';
        END IF;
        v_consumed := fn_cheese_consumed(OLD.id, NULL);
        IF v_consumed > 0 AND (NEW.deleted_at IS NOT NULL OR NEW.quantity < v_consumed) THEN
            SELECT name INTO v_name FROM products WHERE id = OLD.product_id;
            RAISE EXCEPTION 'De % ya salieron % entre mermas y ventas; no puede quedar en menos.', v_name, trim_scale(v_consumed)
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_cheese_batch_outputs_check
BEFORE INSERT OR UPDATE OF product_id, quantity, deleted_at ON cheese_batch_outputs
FOR EACH ROW EXECUTE FUNCTION fn_check_cheese_batch_output();

-- Compra de reventa: solo queso de reventa, piezas enteras y nunca por debajo de lo ya consumido.
CREATE FUNCTION fn_check_cheese_purchase()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_consumed numeric;
BEGIN
    IF NEW.deleted_at IS NULL THEN
        PERFORM fn_check_cheese_product(NEW.product_id, NEW.quantity, 'resale');
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF NEW.product_id <> OLD.product_id THEN
            RAISE EXCEPTION 'El producto de una compra no se cambia.' USING ERRCODE = 'check_violation';
        END IF;
        v_consumed := fn_cheese_consumed(NULL, OLD.id);
        IF v_consumed > 0 AND (NEW.deleted_at IS NOT NULL OR NEW.quantity < v_consumed) THEN
            RAISE EXCEPTION 'De la compra % ya salieron % piezas entre mermas y ventas; no puede quedar en menos.', OLD.code, trim_scale(v_consumed)
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_cheese_purchases_check
BEFORE INSERT OR UPDATE OF product_id, quantity, deleted_at ON cheese_purchases
FOR EACH ROW EXECUTE FUNCTION fn_check_cheese_purchase();

-- Merma, consumo propio o regalo: de una entrada vigente, en piezas enteras si aplica y sin pasar de lo disponible.
-- No se editan: se eliminan (borrado lógico) y se registran de nuevo.
CREATE FUNCTION fn_check_cheese_stock_adjustment()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_in numeric;
    v_product integer;
    v_available numeric;
    v_unit varchar(10);
BEGIN
    IF TG_OP = 'UPDATE' THEN
        RAISE EXCEPTION 'Una merma no se edita; elimínala y regístrala de nuevo.' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.cheese_batch_output_id IS NOT NULL THEN
        SELECT o.quantity, o.product_id INTO v_in, v_product
        FROM cheese_batch_outputs o
        JOIN cheese_batches cb ON cb.id = o.cheese_batch_id
        WHERE o.id = NEW.cheese_batch_output_id AND o.deleted_at IS NULL AND cb.deleted_at IS NULL
        FOR UPDATE OF o;
    ELSE
        SELECT quantity, product_id INTO v_in, v_product
        FROM cheese_purchases
        WHERE id = NEW.cheese_purchase_id AND deleted_at IS NULL
        FOR UPDATE;
    END IF;
    IF v_in IS NULL THEN
        RAISE EXCEPTION 'La tanda o compra elegida ya no está vigente.' USING ERRCODE = 'check_violation';
    END IF;
    SELECT sale_unit INTO v_unit FROM products WHERE id = v_product;
    IF v_unit = 'piece' AND NEW.quantity <> trunc(NEW.quantity) THEN
        RAISE EXCEPTION 'Las piezas van en números enteros.' USING ERRCODE = 'check_violation';
    END IF;
    v_available := v_in - fn_cheese_consumed(NEW.cheese_batch_output_id, NEW.cheese_purchase_id);
    IF NEW.quantity > v_available THEN
        RAISE EXCEPTION 'Solo hay % disponibles; no se pueden descontar %.', trim_scale(v_available), trim_scale(NEW.quantity)
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_cheese_stock_adjustments_check
BEFORE INSERT OR UPDATE OF cheese_batch_output_id, cheese_purchase_id, quantity ON cheese_stock_adjustments
FOR EACH ROW EXECUTE FUNCTION fn_check_cheese_stock_adjustment();

-- Ordeña con tanda: no se elimina y su total no baja de los litros que usó la tanda.
CREATE FUNCTION fn_check_milk_lot_cheese()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_code varchar(30);
    v_used numeric(8,2);
BEGIN
    SELECT code, liters_used INTO v_code, v_used FROM cheese_batches WHERE milk_lot_id = NEW.id AND deleted_at IS NULL;
    IF v_code IS NULL THEN
        RETURN NEW;
    END IF;
    IF NEW.deleted_at IS NOT NULL AND OLD.deleted_at IS NULL THEN
        RAISE EXCEPTION 'La leche de esta ordeña se usó en la tanda %; elimina la tanda primero.', v_code USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.total_liters < v_used THEN
        RAISE EXCEPTION 'La tanda % usó % L de esta ordeña; el total no puede ser menor.', v_code, v_used USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

