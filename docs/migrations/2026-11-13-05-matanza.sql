-- Migración: jornadas de matanza de cabritos en rastro o con matancero externo.
--
-- Varios cabritos se sacrifican el mismo día fuera del rancho; la jornada guarda
-- el rastro o matancero y el pago, y cada cabrito su peso vivo y en canal.
-- Requiere las migraciones 01 a 04.
--
-- Rehace kid_slaughters: si ya había matanzas registradas, la migración se
-- detiene sin cambiar nada.
--
-- Uso (desde la raíz del proyecto, con Docker en marcha):
--   docker compose exec -T db psql -U tecnm_app -d tecnm_template -v ON_ERROR_STOP=1 < docs/migrations/2026-11-13-05-matanza.sql
-- =============================================================================

BEGIN;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM kid_slaughters) THEN
        RAISE EXCEPTION 'Hay matanzas registradas: revísalas antes de migrar.';
    END IF;
END
$$;

DROP TRIGGER tg_kid_slaughters_check ON kid_slaughters;
DROP FUNCTION fn_check_kid_slaughter();

-- Jornada de matanza: cabritos llevados el mismo día a un rastro o matancero externo, con el pago total.
CREATE TABLE slaughter_runs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_date date NOT NULL,
    slaughterhouse varchar(120) NOT NULL,
    cost numeric(10,2),
    notes varchar(255),
    status smallint NOT NULL DEFAULT 1,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by integer,
    updated_at timestamptz,
    deleted_by integer,
    deleted_at timestamptz,
    CONSTRAINT ck_slaughter_runs_cost CHECK (cost IS NULL OR cost >= 0),
    CONSTRAINT ck_slaughter_runs_record_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_slaughter_runs_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_slaughter_runs_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_slaughter_runs_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);

-- Cada cabrito pertenece a una jornada; la fecha, el responsable y las notas pasan a la jornada.
ALTER TABLE kid_slaughters
    DROP CONSTRAINT uq_kid_slaughters_animal_id,
    DROP CONSTRAINT ck_kid_slaughters_weights,
    DROP COLUMN slaughter_date,
    DROP COLUMN responsible_employee_id,
    DROP COLUMN notes,
    ADD COLUMN slaughter_run_id integer NOT NULL,
    ALTER COLUMN live_weight_kg SET NOT NULL,
    ADD CONSTRAINT ck_kid_slaughters_weights CHECK (carcass_weight_kg > 0 AND live_weight_kg >= carcass_weight_kg),
    ADD CONSTRAINT fk_kid_slaughters_slaughter_run_id FOREIGN KEY (slaughter_run_id) REFERENCES slaughter_runs (id);

-- Un cabrito se sacrifica una sola vez (las matanzas eliminadas no cuentan).
CREATE UNIQUE INDEX uq_kid_slaughters_animal_active ON kid_slaughters (animal_id)
    WHERE deleted_at IS NULL;
CREATE INDEX ix_kid_slaughters_slaughter_run_id ON kid_slaughters (slaughter_run_id);

-- Matanza de cabritos: cabrito vigente en el hato, no anterior a su nacimiento y sin retiro de carne
-- en la fecha de la jornada; una canal en un pedido vigente no se elimina.
CREATE FUNCTION fn_check_kid_slaughter()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_date date;
    v_lifecycle varchar(12);
    v_tag varchar(30);
    v_birth date;
    v_allowed date;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.deleted_at IS NOT NULL THEN
        IF OLD.deleted_at IS NULL AND EXISTS (
            SELECT 1 FROM order_items oi
            JOIN orders od ON od.id = oi.order_id
            WHERE oi.kid_slaughter_id = NEW.id AND oi.deleted_at IS NULL AND od.deleted_at IS NULL
              AND od.order_status <> 'cancelled'
        ) THEN
            RAISE EXCEPTION 'La canal ya está en un pedido; no se puede quitar de la matanza.' USING ERRCODE = 'check_violation';
        END IF;
        RETURN NEW;
    END IF;
    SELECT run_date INTO v_date FROM slaughter_runs WHERE id = NEW.slaughter_run_id;
    SELECT lifecycle_status, visual_tag, birth_date INTO v_lifecycle, v_tag, v_birth FROM animals WHERE id = NEW.animal_id;
    IF (TG_OP = 'INSERT' OR NEW.animal_id <> OLD.animal_id) AND v_lifecycle NOT IN ('active', 'slaughtered') THEN
        RAISE EXCEPTION 'El cabrito % ya salió del hato.', v_tag USING ERRCODE = 'check_violation';
    END IF;
    IF v_birth IS NOT NULL AND v_date < v_birth THEN
        RAISE EXCEPTION 'La matanza no puede ser anterior al nacimiento de % (%).', v_tag, to_char(v_birth, 'DD/MM/YYYY')
            USING ERRCODE = 'check_violation';
    END IF;
    v_allowed := fn_withdrawal_allowed_from(NEW.animal_id, 'meat', v_date);
    IF v_allowed IS NOT NULL THEN
        RAISE EXCEPTION 'El cabrito % tiene retiro de carne; puede sacrificarse a partir del %.', v_tag, to_char(v_allowed, 'DD/MM/YYYY')
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_kid_slaughters_check
BEFORE INSERT OR UPDATE OF animal_id, slaughter_run_id, deleted_at ON kid_slaughters
FOR EACH ROW EXECUTE FUNCTION fn_check_kid_slaughter();

-- Jornada de matanza: la fecha no cambia (de ella dependen los retiros y las salidas del hato).
CREATE FUNCTION fn_check_slaughter_run()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.run_date <> OLD.run_date THEN
        RAISE EXCEPTION 'La fecha de una jornada de matanza no se cambia; elimínala y regístrala de nuevo.' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_slaughter_runs_check
BEFORE UPDATE OF run_date ON slaughter_runs
FOR EACH ROW EXECUTE FUNCTION fn_check_slaughter_run();

COMMIT;
