-- Migración: inicio de sesión, roles por negocio y cuentas.
--
-- Las cuentas dejan la columna role y reciben uno o varios roles de la tabla
-- roles (general, ganadería, quesería). Los permisos de cada rol viven en el
-- backend. Requiere las migraciones 01 a 06.
--
-- Si ya había cuentas registradas, la migración se detiene sin cambiar nada.
--
-- Uso (desde la raíz del proyecto, con Docker en marcha):
--   docker compose exec -T db psql -U tecnm_app -d tecnm_template -v ON_ERROR_STOP=1 < docs/migrations/2026-11-16-07-acceso.sql
-- =============================================================================

BEGIN;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM users) THEN
        RAISE EXCEPTION 'Ya hay cuentas registradas: revísalas antes de migrar.';
    END IF;
END
$$;

ALTER TABLE users
    DROP CONSTRAINT ck_users_role,
    DROP COLUMN role,
    ALTER COLUMN email DROP NOT NULL,
    ADD COLUMN full_name varchar(120) NOT NULL,
    ADD COLUMN must_change_password boolean NOT NULL DEFAULT true,
    ADD COLUMN failed_logins smallint NOT NULL DEFAULT 0,
    ADD COLUMN locked_until timestamptz,
    ADD COLUMN last_login_at timestamptz,
    ADD CONSTRAINT ck_users_username CHECK (username ~ '^[a-z0-9._-]{3,32}$'),
    ADD CONSTRAINT ck_users_failed_logins CHECK (failed_logins >= 0);

-- Roles por negocio: general, ganadería o quesería. Los permisos de cada rol se definen en el backend.
CREATE TABLE roles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(24) NOT NULL,
    name varchar(60) NOT NULL,
    division varchar(10) NOT NULL,
    description varchar(255) NOT NULL,
    status smallint NOT NULL DEFAULT 1,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by integer,
    updated_at timestamptz,
    deleted_by integer,
    deleted_at timestamptz,
    CONSTRAINT uq_roles_code UNIQUE (code),
    CONSTRAINT uq_roles_name UNIQUE (name),
    CONSTRAINT ck_roles_division CHECK (division IN ('general', 'livestock', 'cheese')),
    CONSTRAINT ck_roles_record_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_roles_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_roles_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_roles_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);

-- Roles de cada cuenta; una persona puede tener varios.
CREATE TABLE user_roles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL,
    role_id integer NOT NULL,
    status smallint NOT NULL DEFAULT 1,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by integer,
    updated_at timestamptz,
    deleted_by integer,
    deleted_at timestamptz,
    CONSTRAINT ck_user_roles_record_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_user_roles_user_id FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_user_roles_role_id FOREIGN KEY (role_id) REFERENCES roles (id),
    CONSTRAINT fk_user_roles_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_user_roles_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_user_roles_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);

-- Un rol una sola vez por cuenta.
CREATE UNIQUE INDEX uq_user_roles_user_role_active ON user_roles (user_id, role_id)
    WHERE deleted_at IS NULL;
CREATE INDEX ix_user_roles_user_id ON user_roles (user_id);
CREATE INDEX ix_user_roles_role_id ON user_roles (role_id);

