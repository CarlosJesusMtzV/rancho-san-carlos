-- =============================================================================
-- Migración: empadre por temporada, razas sembradas, propósito fijo y situaciones.
--
-- 1. La monta por pareja se vuelve un empadre: un semental con un grupo de
--    hembras (tabla breeding_seasons). La fecha de monta pasa a ser la entrada
--    del semental (breeding_events.start_date).
-- 2. breeds.purpose deja de ser texto libre: es carne, leche o carne-leche.
-- 3. Se siembran las razas (Limousin, Charbray, Simmental, Saanen, Alpina,
--    Toggenburg, Boer, Nubia) y las situaciones del animal (antes "lotes").
--
-- Requiere las migraciones 01 a 08. Si ya hay razas, situaciones o empadres
-- registrados, la migración se detiene sin cambiar nada: empieza con una base
-- nueva (docker compose down -v).
--
-- Uso (desde la raíz del proyecto, con Docker en marcha):
--   docker compose exec -T db psql -U tecnm_app -d tecnm_template -v ON_ERROR_STOP=1 < docs/migrations/2026-11-19-09-empadre-razas-situaciones.sql
-- =============================================================================

BEGIN;

DO $$
DECLARE
    tabla text;
    total bigint;
BEGIN
    FOREACH tabla IN ARRAY ARRAY['breeds', 'animal_lots', 'breeding_events'] LOOP
        EXECUTE format('SELECT count(*) FROM %I', tabla) INTO total;
        IF total > 0 THEN
            RAISE EXCEPTION 'La tabla % ya tiene % registros: empieza con una base nueva antes de migrar.', tabla, total;
        END IF;
    END LOOP;
END
$$;

-- 1. Empadre: encabezado por semental y periodo.
CREATE TABLE breeding_seasons (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species_id smallint NOT NULL,
    male_id integer NOT NULL,
    start_date date NOT NULL,
    notes varchar(255),
    status smallint NOT NULL DEFAULT 1,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by integer,
    updated_at timestamptz,
    deleted_by integer,
    deleted_at timestamptz,
    CONSTRAINT uq_breeding_seasons_id_species UNIQUE (id, species_id),
    CONSTRAINT ck_breeding_seasons_record_status CHECK (status IN (0, 1)),
    CONSTRAINT fk_breeding_seasons_species_id FOREIGN KEY (species_id) REFERENCES species (id),
    CONSTRAINT fk_breeding_seasons_male_id_species_id FOREIGN KEY (male_id, species_id) REFERENCES animals (id, species_id),
    CONSTRAINT fk_breeding_seasons_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_breeding_seasons_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    CONSTRAINT fk_breeding_seasons_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id)
);
CREATE INDEX ix_breeding_seasons_species_id ON breeding_seasons (species_id);
CREATE INDEX ix_breeding_seasons_male_id_species_id ON breeding_seasons (male_id, species_id);

-- La participación de cada hembra se liga a un empadre; la fecha de monta es la entrada del semental.
ALTER TABLE breeding_events RENAME COLUMN mating_date TO start_date;
ALTER TABLE breeding_events ADD COLUMN breeding_season_id integer NOT NULL;
ALTER TABLE breeding_events
    ADD CONSTRAINT uq_breeding_events_season_female UNIQUE (breeding_season_id, female_id),
    ADD CONSTRAINT fk_breeding_events_breeding_season_id_species_id FOREIGN KEY (breeding_season_id, species_id) REFERENCES breeding_seasons (id, species_id);
CREATE INDEX ix_breeding_events_breeding_season_id_species_id ON breeding_events (breeding_season_id, species_id);

-- 2. Propósito de la raza: lista fija.
ALTER TABLE breeds
    ALTER COLUMN purpose TYPE varchar(10),
    ALTER COLUMN purpose SET NOT NULL,
    ADD CONSTRAINT ck_breeds_purpose CHECK (purpose IN ('meat', 'milk', 'meat_milk'));

-- 3. Razas sembradas.
INSERT INTO breeds (species_id, name, purpose) VALUES
    (1, 'Limousin', 'meat'),
    (1, 'Charbray', 'meat'),
    (1, 'Simmental', 'meat_milk'),
    (2, 'Saanen', 'milk'),
    (2, 'Alpina', 'milk'),
    (2, 'Toggenburg', 'milk'),
    (2, 'Boer', 'meat'),
    (2, 'Nubia', 'meat_milk');
SELECT setval(pg_get_serial_sequence('breeds', 'id'), 8);

-- Situaciones del animal (antes "lotes"): opciones fijas por especie.
INSERT INTO animal_lots (code, description, species_id) VALUES
    ('BOV-AGOSTADERO', 'Libre en agostadero', 1),
    ('BOV-BECERRO', 'Encerrada con becerro', 1),
    ('BOV-CUIDADO', 'Cuidado especial', 1),
    ('CAB-CRIAS', 'Con crías', 2),
    ('CAB-SIN-CRIAS', 'Sin crías', 2),
    ('CAB-CUIDADO', 'Cuidado especial', 2);
SELECT setval(pg_get_serial_sequence('animal_lots', 'id'), 6);

COMMIT;
